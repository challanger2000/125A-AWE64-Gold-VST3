// P214 PUBLIC synthetic driver-scoped SF2 tests; user assets never used.
// Test the actual imported instrument/preset resolver and register compiler.
#include "SoundFont.h"
#include "Emu8000Regs.h"
#include <cstdint>
#include <cstdio>
#include <stdexcept>
#include <utility>
#include <vector>
namespace {
void must(bool ok, const char* reason) {
    if(!ok)throw std::runtime_error(reason);
}
SoundFont::Bank fixture(bool presetDecay, bool sf1=false) {
    using namespace SoundFont;
    Bank b;
    b.valid=true;
    b.version=sf1 ? Version::Sf1 : Version::Sf2;
    b.name="public autogenerated no owner media";
    Sample s;
    s.name="public constructed sample";
    s.originalKey=60;
    s.start=1000;
    s.end=3000;
    s.loopStart=1200;
    s.loopEnd=2400;
    b.samples.push_back(s);
    Instrument inst;
    inst.name="public instrument";
    inst.global.Set(Gen::SampleModes,1);
    inst.global.Set(Gen::DecayVolEnv,0);
    Zone iz;
    iz.sampleId=0;
    inst.zones.push_back(iz);
    b.instruments.push_back(std::move(inst));
    Preset p;
    p.bank=1;
    p.program=7;
    p.name="public preset";
    Zone pz;
    pz.instrument=0;
    if(presetDecay)pz.gen.Set(Gen::DecayVolEnv,-1200);
    p.zones.push_back(pz);
    b.presets.push_back(std::move(p));
    return b;
}
SoundFont::VoiceParams compiled(const SoundFont::Bank& b,Awe32::Driver drv) {
    const auto all=b.Select(1,7,60,110);
    must(all.size()==1,"P214 synthetic instrument-zone discovery error");
    return SoundFont::MakeVoiceParams(b,all.front(),60,110,
        0x200020u,0u,drv);
}
}
int main() {
 try {
   const auto b=fixture(true);
   const auto p=compiled(b,Awe32::Driver::Win95);
   const auto bare=compiled(fixture(false),Awe32::Driver::Win95);
   must((p.dcysusv&0x7F)==55 && (bare.dcysusv&0x7F)==39,
        "P214 original Creative SF2 preset decay scope not applied");
   must((p.tremfrq&0xFF)==0xCD && (p.fm2frq2&0xFF)==0xCD,
        "P214 original Creative Win95 SF2 missing LFO default not 0xCD");
   must(p.sampleStart==0x200020u+1000u,
        "P214 original Creative Win95 SF2 start address off by one");
   must((p.psst & Emu8000::kLoopAddressMask)==0x200020u+1199u &&
        (p.csl & Emu8000::kLoopAddressMask)==0x200020u+2399u,
        "P214 original Creative Win95 SF2 loop address off by one");
   // We have no authentic DOS-SF2 capture for these three observations.
   // Crucial: do not silently change that pre-existing separate path.
   const auto dos=compiled(b,Awe32::Driver::Dos);
   must(dos.sampleStart==0x200020u+999u,
        "P214 changed unverified DOS SF2 sample start");
   must((dos.tremfrq&0xFF)==0xC3 && (dos.fm2frq2&0xFF)==0xC3,
        "P214 changed unverified DOS SF2 LFO defaults");
   const auto sf1=fixture(true,true);
   const auto regs=sf1.Select(1,7,60,110);
   must(regs.size()==1 && regs.front().sf2PresetVolDecayRate==-1,
        "P214 altered original Creative SF1/SBK generator precedence");
   std::puts("P214_PUBLIC_ORIGINAL_WIN95_SF2_DECAY_LFO_AND_ADDRESSES_PASS");
   return 0;
 } catch(const std::exception& e) {
   std::fprintf(stderr,"P214_NO_GO %s\n",e.what());return 1;
 }
}
