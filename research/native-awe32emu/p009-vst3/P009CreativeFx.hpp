inline void applyOriginalEmu8000Reverb(Synth& synth,unsigned preset) noexcept {
    if(preset>=8)return;
    constexpr Emu8000::Reg regs[]{
        Emu8000::Reg::INIT1,Emu8000::Reg::INIT2,
        Emu8000::Reg::INIT3,Emu8000::Reg::INIT4};
    for(unsigned i=0;i<28;++i){
        const auto& slot=kOriginalReverbSlots[i];
        synth.Core().Write(regs[slot.group-1],int(slot.voice),
                           kOriginalReverbWords[preset][i]);
    }
}
inline void applyOriginalEmu8000Chorus(Synth& synth,unsigned preset) noexcept {
    if(preset>=8)return;
    const auto& p=kOriginalCreativeChorus[preset];
    auto& c=synth.Core();
    c.Write(Emu8000::Reg::INIT3,9,p.feedback);
    c.Write(Emu8000::Reg::INIT3,12,p.offset);
    c.Write(Emu8000::Reg::INIT4,3,p.depth);
    c.Write(Emu8000::Reg::HWCF,Emu8000::Hwcf::kHWCF4,p.delay);
    c.Write(Emu8000::Reg::HWCF,Emu8000::Hwcf::kHWCF5,p.frequency);
    c.Write(Emu8000::Reg::HWCF,Emu8000::Hwcf::kHWCF6,0x8000u);
    c.Write(Emu8000::Reg::HWCF,Emu8000::Hwcf::kHWCF7,0u);
}
