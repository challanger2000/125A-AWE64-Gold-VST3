#pragma once
// TEMPORARY P006 reference-audio shortcut: tail original 86Box
// AWE32_WAV PCM16 file from a background thread, not VST3 process().
// The existing 86Box-AWE32 executable can be used UNMODIFIED.
// The original emu8k_trace_wav() writes PCM16 stereo 44100 Hz.
// This is not a low-latency production engine. NEVER run alongside
// the passive shared-memory 86Box fork hook (both are SPSC producers).
#include "P006Transport.hpp"
#ifdef _WIN32
#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif
#ifndef NOMINMAX
#define NOMINMAX
#endif
#include <windows.h>
#include <algorithm>
#include <array>
#include <atomic>
#include <cstddef>
#include <cstdint>
#include <thread>
namespace p006 {
class OriginalWavTail final {
    std::atomic<bool> stop_{false};
    std::thread worker_{};
    P006AudioShared* shared_=nullptr;
    wchar_t path_[1024]{};
    static std::uint16_t le16(unsigned char const* b) noexcept {
        return static_cast<std::uint16_t>(
            static_cast<unsigned>(b[0])|(static_cast<unsigned>(b[1])<<8u));
    }
    static std::uint32_t le32(unsigned char const* b) noexcept {
        return static_cast<std::uint32_t>(le16(b))|
            (static_cast<std::uint32_t>(le16(b+2))<<16u);
    }
    static bool recognized(unsigned char const* h) noexcept {
        // Header generated by the ORIGINAL fork's
        // src/sound/snd_emu8k_trace.c (no guessed audio format).
        return h[0]=='R'&&h[1]=='I'&&h[2]=='F'&&h[3]=='F'&&
            h[8]=='W'&&h[9]=='A'&&h[10]=='V'&&h[11]=='E'&&
            h[12]=='f'&&h[13]=='m'&&h[14]=='t'&&h[15]==' '&&
            le32(h+16)==16u&&le16(h+20)==1u&&
            le16(h+22)==2u&&le32(h+24)==44100u&&
            le16(h+34)==16u&&
            h[36]=='d'&&h[37]=='a'&&h[38]=='t'&&h[39]=='a';
    }
    void work() noexcept {
        HANDLE file=INVALID_HANDLE_VALUE;
        std::uint64_t cursor=44u;
        // 2048 frames of precisely the original 16-bit stereo stream.
        std::array<unsigned char,8192> bytes{};
        std::array<float,4096> floats{};
        while(!stop_.load(std::memory_order_acquire)){
            if(file==INVALID_HANDLE_VALUE) {
                file=CreateFileW(path_,GENERIC_READ,
                    FILE_SHARE_READ|FILE_SHARE_WRITE|FILE_SHARE_DELETE,
                    nullptr,OPEN_EXISTING,FILE_ATTRIBUTE_NORMAL,nullptr);
                if(file==INVALID_HANDLE_VALUE){Sleep(15u);continue;}
                unsigned char header[44]{};
                DWORD n=0;
                if(!ReadFile(file,header,44u,&n,nullptr)||
                   n!=44u||!recognized(header)){
                    CloseHandle(file);file=INVALID_HANDLE_VALUE;
                    Sleep(40u);continue;
                }
                cursor=44u;
            }
            LARGE_INTEGER size{};
            if(!GetFileSizeEx(file,&size)) {
                CloseHandle(file);file=INVALID_HANDLE_VALUE;continue;
            }
            if(size.QuadPart<44 || static_cast<std::uint64_t>(
                size.QuadPart)<cursor){
                CloseHandle(file);file=INVALID_HANDLE_VALUE;
                continue;
            }
            const auto available=static_cast<std::uint64_t>(
                size.QuadPart)-cursor;
            if(available<4u){Sleep(5u);continue;}
            const auto count=static_cast<DWORD>(
                std::min<std::uint64_t>(available/4u,2048u)*4u);
            LARGE_INTEGER seek{};
            seek.QuadPart=static_cast<LONGLONG>(cursor);
            if(!SetFilePointerEx(file,seek,nullptr,FILE_BEGIN)){
                CloseHandle(file);file=INVALID_HANDLE_VALUE;continue;
            }
            DWORD n=0;
            if(!ReadFile(file,bytes.data(),count,&n,nullptr)){
                CloseHandle(file);file=INVALID_HANDLE_VALUE;continue;
            }
            const auto frames=n/4u;
            for(std::uint32_t i=0;i<frames;++i){
                const auto left=static_cast<std::int16_t>(
                    le16(bytes.data()+4u*i));
                const auto right=static_cast<std::int16_t>(
                    le16(bytes.data()+4u*i+2u));
                floats[2u*i]=static_cast<float>(left)*(1.f/32768.f);
                floats[2u*i+1u]=static_cast<float>(right)*(1.f/32768.f);
            }
            const auto written=frames>0u && shared_ ?
                p006::write(*shared_,floats.data(),frames):0u;
            cursor+=static_cast<std::uint64_t>(written)*4u;
            if(written<frames||frames==0u)Sleep(5u);
        }
        if(file!=INVALID_HANDLE_VALUE)CloseHandle(file);
    }
public:
    OriginalWavTail()=default;
    OriginalWavTail(OriginalWavTail const&)=delete;
    OriginalWavTail& operator=(OriginalWavTail const&)=delete;
    ~OriginalWavTail(){stopNonRealtime();}
    [[nodiscard]] bool startNonRealtime(P006AudioShared* ring,
                                        const wchar_t* path) noexcept {
        if(worker_.joinable()||ring==nullptr||path==nullptr)return false;
        std::size_t n=0u;
        while(n+1u<sizeof(path_)&&path[n]){
            path_[n]=path[n];++n;
        }
        if(n==0u||path[n])return false;
        path_[n]='\0';shared_=ring;
        stop_.store(false,std::memory_order_release);
        try {worker_=std::thread([this]{work();});}
        catch(...){shared_=nullptr;return false;}
        return true;
    }
    void stopNonRealtime() noexcept {
        stop_.store(true,std::memory_order_release);
        if(worker_.joinable())worker_.join();
        shared_=nullptr;
    }
};
} // namespace p006
#endif
