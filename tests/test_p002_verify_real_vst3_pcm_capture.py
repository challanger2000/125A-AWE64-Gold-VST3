"""Synthetic-only negatives for the actual-VST3 offline PCM WAV auditor.

Never claim these bytes were generated by a genuine original Creative Win95
driver or actual VST3. Real VST3 execution is separately verified in CI.
"""
from pathlib import Path
import struct
import tempfile
import unittest
import wave
from tools import p002_verify_real_vst3_pcm_capture as audit

def make_wav(path, *, late_shift=False, silent=False, early=False,
             wrong_rate=False, truncate=False, mutate_frame=None):
    total = audit.EXPECTED_FRAMES - int(truncate)
    with wave.open(str(path), "wb") as f:
        f.setnchannels(2)
        f.setsampwidth(2)
        f.setframerate(48000 if wrong_rate else 44100)
        pcm = bytearray()
        for frame in range(total):
            note = 137 + int(late_shift)
            value = 0 if silent or frame < note else 4096 + (frame % 100)
            if early and frame == 50:
                value = 200
            if mutate_frame is not None and frame == mutate_frame:
                value += 1
            pcm.extend(struct.pack("<hh", value, -value))
        f.writeframes(pcm)

class RealExportedVst3PrecardWavAuditTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.a = self.root / "actual-host-shaped-a.wav"
        self.b = self.root / "actual-host-shaped-b.wav"
        make_wav(self.a)
        make_wav(self.b)

    def tearDown(self):
        self.temp.cleanup()

    def test_identical_two_distinct_source_shaped_wavs(self):
        report = audit.validate_pair(self.a, self.b)
        self.assertEqual(report["stereo_frames"], 512 * 36)
        self.assertEqual(report["noteon_frame"], 137)
        self.assertGreater(report["peak_pcm16"], 1000)

    def test_mismatched_one_pcm16_lsb_fails(self):
        make_wav(self.b, mutate_frame=1234)
        with self.assertRaisesRegex(ValueError, "differ"):
            audit.validate_pair(self.a, self.b)

    def test_one_frame_shift_is_not_autocorrected(self):
        make_wav(self.b, late_shift=True)
        with self.assertRaisesRegex(ValueError, "differ"):
            audit.validate_pair(self.a, self.b)

    def test_changed_note_while_before_note_window_rejected(self):
        make_wav(self.b, early=True)
        with self.assertRaisesRegex(ValueError, "before MIDI NoteOn"):
            audit.inspect(self.b)

    def test_wrong_rate_and_short_file_refused(self):
        make_wav(self.b, wrong_rate=True)
        with self.assertRaisesRegex(ValueError, "44100"):
            audit.inspect(self.b)
        make_wav(self.b, truncate=True)
        with self.assertRaisesRegex(ValueError, "file length"):
            audit.inspect(self.b)

    def test_both_silent_or_same_file_no_go(self):
        make_wav(self.b, silent=True)
        with self.assertRaisesRegex(ValueError, "silent"):
            audit.inspect(self.b)
        with self.assertRaisesRegex(ValueError, "independently"):
            audit.validate_pair(self.a, self.a)

    def test_header_mutation_not_accepted(self):
        bytes_ = bytearray(self.b.read_bytes())
        bytes_[4] ^= 1
        self.b.write_bytes(bytes_)
        with self.assertRaisesRegex(ValueError, "RIFF sizes"):
            audit.inspect(self.b)


if __name__ == "__main__":
    unittest.main()
