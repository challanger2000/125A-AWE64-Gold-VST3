#!/usr/bin/env python3
"""P001 direct original-fork chip PCM vs adapter, destructive negative oracles.

Synthetic waveform and register stream are generated by compiled original
snd_emu8k.c, NOT by the adapter. This does not replace original 86Box VM
EMU8K_TRACE/AWE32_WAV with the Creative driver and exact private ROM.
"""
import pathlib
import subprocess
import sys
import tempfile
import wave

def run(*args):
    proc = subprocess.run(list(map(str,args)),capture_output=True,text=True,timeout=120)
    return proc.returncode,proc.stdout+proc.stderr

def require(ok,what):
    if not ok: raise AssertionError(what)

def main():
    require(len(sys.argv)==3,"need direct-fork fixture executable and replay executable")
    direct,replay=map(pathlib.Path,sys.argv[1:])
    with tempfile.TemporaryDirectory(prefix="p001-direct-fork-") as d:
        root=pathlib.Path(d)
        code,out=run(direct,root)
        require(code==0,"direct fork fixture FAILED:\n"+out)
        print(out.strip())
        rom,trace,original=(root/f for f in ("synthetic.raw","fork.trace","fork.wav"))
        def compare(reference=original,tracefile=trace,dest="native.wav"):
            return run(replay,"--rom",rom,"--trace",tracefile,
                       "--fork-wav",reference,"--out",root/dest)
        code,out=compare()
        require(code==0,"adapter differs from direct unmodified fork:\n"+out)
        require("IDENTICAL: 4410 stereo frames, 8820 individual samples" in out,
                "positive verification wrong duration/claim: "+out)
        print("POSITIVE",out.strip())
        with wave.open(str(original),"rb") as f:
            require(f.getnframes()==4410 and f.getframerate()==44100,
                    "positive independent WAV invalid")
            pcm=f.readframes(4410)
        require(any(pcm),"silence would invalidate comparison")

        # Mutate one genuine fork PCM sample at a known nonzero sample,
        # without changing format, duration, or original chip/reg stimulus.
        corrupted=bytearray(original.read_bytes())
        offset=44+4*2100+2
        corrupted[offset]^=0x01
        mutant=root/"mutant.wav"; mutant.write_bytes(corrupted)
        code,out=compare(mutant,dest="mutated-output.wav")
        require(code==11 and "first differing frame 2100 channel 1" in out,
                "PCM mismatch negative control not detected:\n"+out)
        print("NEGATIVE_PCM",out.strip())

        # Mutate one *recorded original core* register-read expectation.
        rows=trace.read_text().splitlines()
        found=False
        for i,row in enumerate(rows):
            if row.startswith("R "):
                parts=row.split()
                parts[-1]=f"{(int(parts[-1],16)^1):04X}"
                rows[i]=" ".join(parts)
                found=True;break
        require(found,"no readback available for adversarial test")
        badtrace=root/"bad.trace";badtrace.write_text("\n".join(rows)+"\n")
        code,out=compare(tracefile=badtrace,dest="bad-read-output.wav")
        require(code==8 and "FAIL register read" in out,
                "register negative control not detected:\n"+out)
        print("NEGATIVE_REGISTER",out.strip())

        code,out=compare(reference=root/"absent.wav",dest="absent-output.wav")
        require(code==4 and "NOT VERIFIED" in out,
                "missing independent WAV incorrectly counted as PASS:\n"+out)
        print("NEGATIVE_MISSING_WAV",out.strip())
        print("P001 SYNTHETIC DIRECT-FORK / ADAPTER PCM AND NEGATIVE CONTROLS PASS")
        print("INDEPENDENT VM/CREATIVE ORIGINAL-ROM PARITY STILL NOT RUN")
if __name__=="__main__":
    try:main()
    except Exception as e:
        print("FAIL",e,file=sys.stderr);sys.exit(1)
