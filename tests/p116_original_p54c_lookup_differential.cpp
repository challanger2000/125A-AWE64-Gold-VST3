// P116 independent full public original 86Box switch+table DIFFERENTIAL.
// No original Win95 private files, no guesses for executed guest paths.
#include "P116OriginalP54cOpcodeLookup.hpp"
#include <cstdint>
#include <fstream>
#include <iostream>
#include <string>

using awe64::research_p116::originalP54cLookup;
#define CHECK(x) do {if(!(x)){std::cerr<<"P116_FAIL line="<<__LINE__<<" "<<#x<<"\n";return 1;}}while(false)

int main(int argc,char** argv) {
    CHECK(argc==2);
    std::ifstream input(argv[1]);
    CHECK(input.good());
    std::string prefix,opcode,fetch,timing,dependency,selected;
    std::size_t count=0,integerCount=0,mod3Count=0;
    // These records were generated by executing the ORIGINAL 86Box
    // source switch + original uint64_t C array initializers.
    while(input>>prefix>>opcode>>fetch>>timing>>dependency>>selected) {
        const auto p=static_cast<std::uint8_t>(std::stoul(prefix,nullptr,16));
        const auto op=static_cast<std::uint8_t>(std::stoul(opcode,nullptr,16));
        const auto f=static_cast<std::uint32_t>(std::stoul(fetch,nullptr,16));
        const auto wantTiming=std::stoull(timing,nullptr,16);
        const auto wantDependency=std::stoull(dependency,nullptr,16);
        const auto wantSelected=std::stoul(selected,nullptr,16);
        const auto got=originalP54cLookup(p,op,f);
        if (!got || got->timing_word!=wantTiming ||
            got->dependency_word!=wantDependency ||
            got->selected_opcode!=wantSelected) {
            std::cerr<<"P116_ORIGINAL_SWITCH_DIFFERENTIAL_FAIL "
                     <<"row="<<count<<" prefix="<<prefix
                     <<" op="<<opcode<<" fetch="<<fetch<<"\n";
            return 1;
        }
        const auto pair=(wantTiming>>29u)&7ull;
        const auto sourceInteger=(wantTiming!=0u && pair<=3u &&
             (wantDependency & (0x3ffull<<24u))==0u &&
             (wantDependency & (3ull<<22u))==0u);
        CHECK(got->integer_subset==sourceInteger);
        ++count;
        if(got->integer_subset)++integerCount;
        if((f&0xc0u)==0xc0u)++mod3Count;
    }
    // 10 prefixes * 256 opcodes * 16 representative ModR/M fetch values.
    CHECK(count==40960u);
    CHECK(integerCount>5000u);
    CHECK(mod3Count>0u);
    const auto jcc=originalP54cLookup(0u,0x75u,0u);
    const auto near=originalP54cLookup(0x0fu,0x85u,0u);
    const auto reg=originalP54cLookup(0u,0x01u,0xc0u);
    const auto mem=originalP54cLookup(0u,0x01u,0x00u);
    CHECK(jcc && jcc->integer_subset);
    CHECK(near && near->integer_subset);
    CHECK(reg && mem && reg->timing_word!=mem->timing_word);
    std::cout<<"P116_ORIGINAL_P54C_TABLE_SWITCH_DIFF_PASS "
             <<"pairs="<<count<<" integer_subset="<<integerCount
             <<" mod3="<<mod3Count
             <<" original_executed_guest=NOT_TESTED"
             <<" autonomous_noteon=NO_GO\n";
    return 0;
}
